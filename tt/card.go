package tt

import (
	"os"
	"strconv"
	"unsafe"
)

// Card is how a program that tessc compiled for the card reaches it. Such a
// program runs main as ordinary Go on the host. Code that tessc generates
// installs a Card with UseCard (package tt/card provides one, which talks to
// a helper process that owns the card), and from then on LoadBytes,
// OpenBytes and LoadDetector also put their data on the card, and Launch
// runs workers there. Programs do not use Card themselves.
type Card interface {
	LoadBytes(path string) int    // copies the file to the card; returns a handle
	OpenBytes(path string) int    // lets the card's workers read the file on demand
	LoadDetector(path string) int // puts the detector's weights on the card
	BytesRead(handle int) int     // bytes of an OpenBytes file the card's workers have read
	Cores() int                   // Tensix cores for workers, on all the card's chips
	// Launch runs the kernel on n workers and returns their records,
	// recordBytes each, worker 0's first.
	Launch(k Kernel, n, recordBytes int, args []CardArg) []byte
	Close() // releases the card
}

var theCard Card

// Cores is the number of Tensix cores the card has for workers, one per
// worker: tt.Parallel(tt.Cores(), ...) uses them all. An n300 has 128 (64
// on each of its two chips). Run on the CPU, without a card, Cores is 128
// too, or what the environment variable TESSERA_CORES says, so that the
// CPU splits the work as the card would.
func Cores() int {
	if theCard != nil {
		return theCard.Cores()
	}
	if n, err := strconv.Atoi(os.Getenv("TESSERA_CORES")); err == nil && n > 0 {
		return n
	}
	return 128
}

// UseCard makes the program use the card from now on. Code generated by
// tessc calls it before main starts.
func UseCard(c Card) { theCard = c }

// CloseCard releases the card. Code generated by tessc calls it when main
// returns.
func CloseCard() {
	if theCard != nil {
		theCard.Close()
		theCard = nil
	}
}

// Kernel describes the worker kernel that tessc compiled from the function
// given to Parallel.
type Kernel struct {
	Name      string     // its source file in the program's kernel directory
	Scratch   int        // bytes of L1 scratch each worker needs for its arrays
	Capacity  int        // how many results one worker can append
	Positions []Position // the places in the Go source where a worker can fail
}

// Position is a place in the Go source where a worker can fail at run time.
type Position struct {
	Where string // file:line:col
	What  string // what can go wrong there
}

// CardArg is one of main's variables that a worker uses, passed to the card.
type CardArg struct {
	Kind  int // ArgInt, ArgBool, ArgBytes, ArgDetector or ArgString
	Value int64
	Text  string // ArgString's string
}

// The kinds of CardArg.
const (
	ArgInt = iota
	ArgBool
	ArgBytes
	ArgDetector
	ArgString
)

// IntArg passes an integer variable to the workers.
func IntArg(v int64) CardArg { return CardArg{Kind: ArgInt, Value: v} }

// StringArg passes a string variable to the workers. It travels with the
// workers' other arguments, so it can be at most 1024 bytes long.
func StringArg(s string) CardArg { return CardArg{Kind: ArgString, Text: s} }

// BoolArg passes a bool variable to the workers.
func BoolArg(v bool) CardArg {
	if v {
		return CardArg{Kind: ArgBool, Value: 1}
	}
	return CardArg{Kind: ArgBool}
}

// BytesArg passes a byte array that is on the card to the workers.
func BytesArg(b Bytes) CardArg {
	if b.dev == 0 {
		fatalf("tt.Launch: a tt.Bytes the workers use was made before the card was in use")
	}
	return CardArg{Kind: ArgBytes, Value: int64(b.dev - 1)}
}

// DetectorArg passes a detector that is on the card to the workers.
func DetectorArg(d Detector) CardArg {
	if d.dev == 0 {
		fatalf("tt.Launch: the tt.Detector the workers use was made before the card was in use")
	}
	return CardArg{Kind: ArgDetector, Value: int64(d.dev - 1)}
}

// Launch is Parallel for a program compiled by tessc: tessc rewrites each
// tt.Parallel(n, work) into tt.Launch(kernel, n, work, args), where kernel is
// work compiled for the card and args are the variables of main that work
// uses. With a card in use the workers run there; otherwise Launch is
// Parallel.
//
// T is a struct of integers and bools (tessc checks this), laid out on the
// card exactly as in Go, so a record is copied as it is.
func Launch[T any](k Kernel, n int, work func(w int, out *List[T]), args []CardArg) []T {
	if theCard == nil {
		return Parallel(n, work)
	}
	if n <= 0 {
		fatalf("tt.Parallel: %d workers", n)
	}
	var zero T
	size := int(unsafe.Sizeof(zero))
	raw := theCard.Launch(k, n, size, args)
	out := make([]T, len(raw)/size)
	if len(out) > 0 {
		copy(unsafe.Slice((*byte)(unsafe.Pointer(&out[0])), len(out)*size), raw)
	}
	return out
}
