type manifestArray struct {
	Name string `json:"name"`
	Path string `json:"path"`
}

func manifest(p *Program, k *Kernel) string {
	m := struct {
		Program    string          `json:"program"`
		Rows       int             `json:"rows"`
		Cols       int             `json:"cols"`
		Tiles      int             `json:"tiles"`
		Inputs     []manifestArray `json:"inputs"`
		Outputs    []manifestArray `json:"outputs"`
		DestSlots  int             `json:"dest_slots"`
		FullSync   bool            `json:"dest_full_sync"`
		SFPUInstrs int             `json:"sfpu_instructions"`
	}{Program: p.Name, Rows: p.Rows, Cols: p.Cols, Tiles: p.tiles(), DestSlots: k.Slots, FullSync: k.FullSync, SFPUInstrs: len(k.Instrs)}
	for _, in := range p.Inputs {
		m.Inputs = append(m.Inputs, manifestArray{in.Name, in.Path})
	}
	for _, o := range p.Outputs {
		m.Outputs = append(m.Outputs, manifestArray{o.Name, o.Path})
	}
	out, _ := json.MarshalIndent(m, "", "  ")
	return string(out) + "\n"
}
