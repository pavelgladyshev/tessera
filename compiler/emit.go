// Circular-buffer numbering: inputs use c_0..c_15, outputs c_16..c_31.
const (
	maxArrays   = 16
	firstOutCB  = 16
	generatedBy = "Generated by tessc. Change the Go source and run tessc again; " +
		"edits here are lost on the next compile."
)

// Emit writes the Metalium project for p into dir and returns the files written.
func Emit(p *Program, k *Kernel, dir string) ([]string, error) {
	if len(p.Inputs) > maxArrays || len(p.Outputs) > maxArrays {
		return nil, fmt.Errorf("v0 supports at most %d input and %d output arrays", maxArrays, maxArrays)
	}
	files := map[string]string{
		"CMakeLists.txt":      cmakeLists(p),
		"build.sh":            buildScript(p),
		"host.cpp":            hostProgram(p, k),
		"kernels/reader.cpp":  readerKernel(p),
		"kernels/compute.cpp": computeKernel(p, k),
		"kernels/writer.cpp":  writerKernel(p),
		"program.json":        manifest(p, k),
	}
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	var written []string
	for _, name := range names {
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return nil, err
		}
		mode := os.FileMode(0o644)
		if strings.HasSuffix(name, ".sh") {
			mode = 0o755
		}
		if err := os.WriteFile(path, []byte(files[name]), mode); err != nil {
			return nil, err
		}
		written = append(written, path)
	}
	return written, nil
}

func baseName(path string) string { return filepath.Base(path) }

func cident(s string) string {
	var b strings.Builder
	for _, r := range s {
		if r < 128 && (r == '_' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9') {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
	}
	return b.String()
}

// cstring quotes s as a C++ string literal.
func cstring(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range []byte(s) {
		switch {
		case r == '"' || r == '\\':
			b.WriteByte('\\')
			b.WriteByte(r)
		case r < 0x20 || r >= 0x7f:
			fmt.Fprintf(&b, "\\x%02x\"\"", r)
		default:
			b.WriteByte(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func (p *Program) tiles() int { return (p.Elems() + 1023) / 1024 }

